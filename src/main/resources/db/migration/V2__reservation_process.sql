CREATE TABLE reservation_process (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL REFERENCES app_user (id),
    reservation_process_id VARCHAR(100) NOT NULL,
    hold_id                VARCHAR(100) NOT NULL,
    professional_id        BIGINT       NOT NULL,
    slot_date              DATE         NOT NULL,
    slot_start_time        TIME         NOT NULL,
    external_patient_id    VARCHAR(100) NOT NULL,
    status                 VARCHAR(30)  NOT NULL,
    expires_at             TIMESTAMPTZ  NOT NULL,
    created_date           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_modified_date     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_reservation_process_process_id UNIQUE (reservation_process_id),
    CONSTRAINT uk_reservation_process_hold_id UNIQUE (hold_id),
    CONSTRAINT ck_reservation_process_status CHECK (status IN
        ('HELD', 'WAITING_FOR_PHONE', 'PHONE_SUBMITTED', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'FAILED'))
);

CREATE INDEX idx_reservation_process_user ON reservation_process (user_id);